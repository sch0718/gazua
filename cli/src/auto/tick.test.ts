import { expect, it } from 'vitest';
import { tickDown, tickOf, tickUp } from './tick';

it('호가 경계에서 올림과 내림을 적용한다', () => {
  for (const [price, tick, up, down] of [[1999.1, 1, 2000, 1999], [2000.1, 5, 2005, 2000], [4999, 5, 5000, 4995], [5001, 10, 5010, 5000], [19999, 10, 20000, 19990], [20001, 50, 20050, 20000], [49999, 50, 50000, 49950], [50001, 100, 50100, 50000], [199999, 100, 200000, 199900], [200001, 500, 200500, 200000], [499999, 500, 500000, 499500], [500001, 1000, 501000, 500000], [10000, 10, 10000, 10000]]) {
    expect(tickOf(price)).toBe(tick);
    expect(tickUp(price)).toBe(up);
    expect(tickDown(price)).toBe(down);
  }
});
